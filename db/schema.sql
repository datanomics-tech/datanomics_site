-- DATANOMICS TECHNOLOGIES Ltd: database schema (MySQL 8+ / MariaDB 10.6+)
-- List-type fields (solutions, tags, ...) are stored as JSON text.

CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  last_login DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(80) PRIMARY KEY,
  v TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS verticals (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  division CHAR(1) NOT NULL,
  icon VARCHAR(40) NOT NULL DEFAULT 'i-grid',
  short_name VARCHAR(80) NOT NULL,
  title VARCHAR(200) NOT NULL,
  summary TEXT NOT NULL,
  intro TEXT NOT NULL,
  solutions TEXT NULL,
  customers TEXT NULL,
  deliverables TEXT NULL,
  technologies TEXT NULL,
  note TEXT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS projects (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  category VARCHAR(80) NOT NULL,
  tags TEXT NULL,
  stack VARCHAR(255) NULL,
  summary TEXT NOT NULL,
  details TEXT NULL,
  url VARCHAR(500) NULL,
  is_live TINYINT(1) NOT NULL DEFAULT 0,
  cover_image VARCHAR(500) NULL,
  color_a VARCHAR(9) NOT NULL DEFAULT '#0D6EFD',
  color_b VARCHAR(9) NOT NULL DEFAULT '#00C853',
  icon VARCHAR(40) NOT NULL DEFAULT 'i-layers',
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS team (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  role VARCHAR(160) NOT NULL,
  bio TEXT NULL,
  photo VARCHAR(500) NULL,
  linkedin VARCHAR(500) NULL,
  x_url VARCHAR(500) NULL,
  is_lead TINYINT(1) NOT NULL DEFAULT 0,
  is_placeholder TINYINT(1) NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS testimonials (
  id INT AUTO_INCREMENT PRIMARY KEY,
  quote TEXT NOT NULL,
  author VARCHAR(160) NOT NULL,
  company VARCHAR(200) NULL,
  rating TINYINT NOT NULL DEFAULT 5,
  is_sample TINYINT(1) NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS insight_categories (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS insight_topics (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  keywords VARCHAR(500) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS feeds (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  url VARCHAR(700) NOT NULL,
  category_id INT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  last_fetched DATETIME NULL,
  last_status VARCHAR(255) NULL,
  CONSTRAINT fk_feed_cat FOREIGN KEY (category_id) REFERENCES insight_categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS insights (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(400) NOT NULL,
  summary TEXT NULL,
  body MEDIUMTEXT NULL,
  url VARCHAR(700) NULL,
  url_hash CHAR(40) NULL UNIQUE,
  source VARCHAR(160) NULL,
  image_url VARCHAR(700) NULL,
  category_id INT NULL,
  topics VARCHAR(500) NULL,
  origin ENUM('manual','feed') NOT NULL DEFAULT 'manual',
  status ENUM('pending','published','hidden') NOT NULL DEFAULT 'pending',
  featured TINYINT(1) NOT NULL DEFAULT 0,
  read_minutes TINYINT NULL,
  published_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_status_date (status, published_at),
  CONSTRAINT fk_ins_cat FOREIGN KEY (category_id) REFERENCES insight_categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS contacts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  company VARCHAR(200) NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(60) NULL,
  service VARCHAR(200) NULL,
  message TEXT NOT NULL,
  source_page VARCHAR(255) NULL,
  status ENUM('new','read','replied','archived') NOT NULL DEFAULT 'new',
  notes TEXT NULL,
  sheet_synced TINYINT(1) NOT NULL DEFAULT 0,
  sheet_error VARCHAR(255) NULL,
  ip VARCHAR(64) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_contacts_status (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS subscribers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
